#!/usr/bin/env bash
# soak_fuzz.sh - crash-free random step/BP soak against a fixture inferior.
# Module: release/test (shell).
# Owns: CI-bounded and full-hour seeded headless fuzz loops.
# Depends: antinomia headless CLI; long-lived ELF fixture (loop_inferior).
set -euo pipefail

ANTINOMIA=""
INFERIOR=""
SECONDS_BUDGET="${SOAK_SECONDS:-90}"
SEED="${SOAK_SEED:-1}"
ROUNDS_CAP="${SOAK_ROUNDS:-0}"
SYM_BP="loop_inferior:antinomia_touch"
SYM_MARK="loop_inferior:antinomia_marker"

usage() {
  cat >&2 <<'EOF'
Usage: scripts/soak_fuzz.sh --antinomia PATH --inferior PATH
                            [--seconds N] [--seed N] [--rounds N]

CI default: 90s. Full Phase 4 gate soak: --seconds 3600 (or SOAK_SECONDS=3600).
EOF
  exit 2
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --antinomia) ANTINOMIA="${2:-}"; shift 2 ;;
    --inferior) INFERIOR="${2:-}"; shift 2 ;;
    --seconds) SECONDS_BUDGET="${2:-}"; shift 2 ;;
    --seed) SEED="${2:-}"; shift 2 ;;
    --rounds) ROUNDS_CAP="${2:-}"; shift 2 ;;
    -h|--help) usage ;;
    *) echo "unknown arg: $1" >&2; usage ;;
  esac
done

[[ -n "$ANTINOMIA" && -n "$INFERIOR" ]] || usage
[[ -f "$ANTINOMIA" ]] || { echo "antinomia not found: $ANTINOMIA" >&2; exit 1; }
[[ -f "$INFERIOR" ]] || { echo "inferior not found: $INFERIOR" >&2; exit 1; }
chmod +x "$ANTINOMIA" 2>/dev/null || true

# Seed bash RANDOM for reproducible op picks (CI + full soak).
RANDOM="$SEED"
ORIG_SEED="$SEED"

rand_n() {
  local n="$1"
  echo $((RANDOM % n))
}

write_round_script() {
  local out="$1"
  local ops i choice
  ops=$((3 + $(rand_n 6)))
  {
    echo "# soak round generated by scripts/soak_fuzz.sh"
    echo "init ${INFERIOR}"
    echo "wait_event 5000"
    echo "wait_event 5000"
    for ((i = 0; i < ops; i++)); do
      choice=$(rand_n 8)
      case "$choice" in
        0)
          echo "bp ${SYM_BP}"
          echo "bplist"
          ;;
        1)
          echo "bp ${SYM_MARK}"
          echo "bc ${SYM_MARK}"
          ;;
        2)
          echo "bp ${SYM_BP}"
          echo "run"
          echo "wait_event 3000"
          echo "sti"
          ;;
        3)
          echo "bp ${SYM_BP}"
          echo "run"
          echo "wait_event 3000"
          echo "sto"
          ;;
        4)
          echo "regs"
          echo "d rip --len 32"
          ;;
        5)
          echo "sti"
          echo "sti"
          ;;
        6)
          echo "bp ${SYM_BP}"
          echo "run"
          echo "wait_event 2000"
          echo "pause"
          echo "wait_event 2000"
          ;;
        *)
          echo "bplist"
          echo "modules"
          ;;
      esac
    done
    echo "kill"
  } >"$out"
}

run_headless() {
  local script="$1" out="$2" err="$3"
  if command -v timeout >/dev/null 2>&1; then
    timeout --signal=KILL 45s "$ANTINOMIA" headless "$script" >"$out" 2>"$err"
    return $?
  fi
  "$ANTINOMIA" headless "$script" >"$out" 2>"$err"
  return $?
}

WORKDIR="$(mktemp -d "${TMPDIR:-/tmp}/antinomia-soak.XXXXXX")"
cleanup() { rm -rf "$WORKDIR"; }
trap cleanup EXIT

START=$(date +%s)
ROUND=0
echo "soak: start seconds=${SECONDS_BUDGET} seed=${ORIG_SEED} antinomia=${ANTINOMIA}" >&2

while true; do
  NOW=$(date +%s)
  ELAPSED=$((NOW - START))
  if (( ELAPSED >= SECONDS_BUDGET )); then
    break
  fi
  if [[ "$ROUNDS_CAP" != "0" && "$ROUND" -ge "$ROUNDS_CAP" ]]; then
    break
  fi
  ROUND=$((ROUND + 1))
  SCRIPT="${WORKDIR}/round-${ROUND}.re"
  OUT="${WORKDIR}/round-${ROUND}.out"
  ERR="${WORKDIR}/round-${ROUND}.err"
  write_round_script "$SCRIPT"

  set +e
  run_headless "$SCRIPT" "$OUT" "$ERR"
  rc=$?
  set -e

  if (( rc == 137 || rc == 124 )); then
    echo "soak: FAIL round=${ROUND} timeout/kill rc=${rc}" >&2
    cat "$ERR" >&2 || true
    exit 1
  fi
  if (( rc >= 128 )); then
    echo "soak: FAIL round=${ROUND} debugger signal rc=${rc}" >&2
    cat "$ERR" >&2 || true
    exit 1
  fi
  if ! grep -q '"schema":"antinomia/1"' "$OUT"; then
    echo "soak: FAIL round=${ROUND} missing schema in stdout" >&2
    cat "$OUT" >&2 || true
    cat "$ERR" >&2 || true
    exit 1
  fi
  if ! grep -q '"tool":"headless"' "$OUT"; then
    echo "soak: FAIL round=${ROUND} missing headless tool frame" >&2
    cat "$OUT" >&2 || true
    exit 1
  fi
  if ! grep -q '"exit":' "$OUT"; then
    echo "soak: FAIL round=${ROUND} missing headless exit field" >&2
    cat "$OUT" >&2 || true
    exit 1
  fi
done

END=$(date +%s)
echo "soak: ok rounds=${ROUND} seconds=$((END - START)) seed=${ORIG_SEED}" >&2
exit 0
